	uint32_t dsqrtRes[4] = { 0,1,1,2 };

	

	constexpr BIT_SIZE dsqrt_bit_bsm(uint32_t n) {
		BIT_SIZE res = 0;
		while (n != 1) {
			n >>= 1;
			res++;
		}
		return res;
	}

	

	int15::signal_t int15::sqrt(int15::ulong_signal_t x) {
		if (x > DSQRT_MAX_X)
			x = DSQRT_MAX_X;
		if (x < 4) {
			return dsqrtRes[x];
		}
		else {
			BIT_SIZE ix = dsqrt_bit_bsm(x) - 2;
			return ((x * dsqrtGainArray[ix]) >> dsqrtShift[ix]) + dsqrtOffsetArray[ix];
		}
	}


